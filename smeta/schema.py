# -*- coding: utf-8 -*-
"""Единая схема нормализованной сметы.

Всё, что парсер вытащил из любого источника (xlsx Гранд-Сметы, АРПС, позже PDF),
приводится к этим колонкам. Дальше по пайплайну ходит только эта таблица.
"""

COLUMNS = [
    "file",        # имя исходного файла
    "sheet",       # лист
    "excel_row",   # номер строки в исходнике — нужен, чтобы в протоколе показать, где смотреть
    "kind",        # position | overhead | profit | section | subtotal | total | unknown
    "section",     # раздел сметы
    "subsection",  # блок работ внутри раздела
    "num",         # № п/п
    "code",        # шифр расценки / обоснование
    "name",        # наименование работ и затрат
    "unit",        # единица измерения
    "qty",         # объём
    "price",       # цена за единицу
    "coef",        # итоговый повышающий коэффициент (произведение)
    "coef_text",   # исходная запись коэффициентов — для протокола
    "total",       # сумма по позиции
    "ozp",         # основная зарплата
    "emm",         # эксплуатация машин и механизмов
    "mat",         # материалы
    "pct",         # процент для строк НР/СП
    "index",       # индекс пересчёта в текущий уровень цен
    "price_current",  # цена за единицу в текущем уровне цен
    "price_level",    # в каком уровне цен посчитана позиция
    "volume_calc",    # как получен объём: «Объём: 1,9*1,5*8+1,2*1,5»
    "qty_unit",    # количество на единицу измерения (до коэффициентов)
    "total_current",       # стоимость в текущем уровне цен
    "total_with_overhead", # «Всего по позиции»: расценка + НР + СП
    "nr_pct",      # накладные расходы, % (с строки НР блока)
    "sp_pct",      # сметная прибыль, %
    "work_type",   # вид работ из строки НР/СП — по нему норматив 812/пр и 774/пр
    "parent_row",  # строка позиции, к которой относится НР/СП
    "resources",   # сколько строк ресурсов внутри позиции
    "components",  # составляющие стоимости: ОЗП, ЭМ, материалы — каждая со своим коэффициентом
    "nr_sum",      # сумма накладных расходов по позиции
    "sp_sum",      # сумма сметной прибыли по позиции
]

KIND_POSITION = "position"
KIND_OVERHEAD = "overhead"   # накладные расходы
KIND_PROFIT = "profit"       # сметная прибыль
KIND_SECTION = "section"
KIND_SUBTOTAL = "subtotal"
KIND_TOTAL = "total"
KIND_UNKNOWN = "unknown"
