"""Справочник допустимых НР и СП по видам работ.

ВНИМАНИЕ: значения ниже — рабочая заглушка для прототипа. Боевые нормативы берутся
из приказов Минстроя 812/пр (накладные расходы) и 774/пр (сметная прибыль): там
разбивка по видам работ подробнее и есть понижающие коэффициенты по условиям
применения. Перед показом заказчику таблицу заменить на выгрузку из приказов.

Принцип: если вида работ в справочнике нет, возвращаем None и правило молчит.
Выдавать замечание «норматив неизвестен» на каждую вторую позицию — это шум,
в котором тонет всё остальное. Разнобой процентов внутри одного вида работ
ловится отдельным правилом, которому справочник не нужен вовсе.
"""

# ключевое слово в названии вида работ или раздела -> (НР %, СП %)
NORMS = {
    "земляные": (95, 50),
    "бетонные": (105, 64),
    "железобетон": (105, 64),
    "свайные": (105, 60),
    "каменные": (100, 60),
    "металлические конструкции": (90, 85),
    "деревянные": (100, 55),
    "кровельные": (108, 55),
    "изоляционные": (100, 50),
    "отделочные": (105, 55),
    "внутренние санитарно-технические": (128, 83),
    "электромонтажные": (95, 65),
    "благоустройство": (95, 50),
}

TOLERANCE_PCT = 5  # допуск на отклонение от норматива, процентных пунктов


def norm_for(name):
    """Норматив по названию вида работ или раздела. Не нашли — None."""
    s = (name or "").lower()
    if not s:
        return None
    for key, value in NORMS.items():
        if key in s:
            return value
    return None
